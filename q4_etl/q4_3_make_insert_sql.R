# Question 4.3 without a local server: turns output/hn_clean.csv into a SQL
# script of INSERT statements (sql/02_insert_data.sql). Paste
# sql/01_create_table.sql followed by this file into an online PostgreSQL
# such as db-fiddle.com to import the data, then run sql/03_analysis.sql.
# Run from the q4_etl folder.

suppressPackageStartupMessages({
  library(readr)
  library(dplyr)
})

if (!file.exists("output/hn_clean.csv")) {
  stop("output/hn_clean.csv not found. Run q4_2_clean.R first (from the q4_etl folder).", call. = FALSE)
}

hn_clean <- read_csv("output/hn_clean.csv", col_types = cols(.default = col_character()), na = "")

numeric_cols <- c("item_id", "rank", "page", "points", "comments", "age_hours", "points_per_hour", "title_words")
boolean_cols <- c("points_imputed", "comments_imputed")

# Text and timestamps become quoted literals (PostgreSQL casts ISO timestamps
# itself); numbers and booleans stay bare; missing values become NULL.
sql_literal <- function(values, column) {
  literal <- if (column %in% numeric_cols) {
    values
  } else if (column %in% boolean_cols) {
    toupper(values)
  } else {
    paste0("'", gsub("'", "''", values, fixed = TRUE), "'")
  }
  ifelse(is.na(values) | values == "", "NULL", literal)
}

literals <- mapply(sql_literal, hn_clean, names(hn_clean), SIMPLIFY = FALSE)
rows <- do.call(paste, c(literals, sep = ", "))

insert_sql <- c(
  sprintf("-- %d rows from output/hn_clean.csv, generated by q4_3_make_insert_sql.R", nrow(hn_clean)),
  sprintf("INSERT INTO hn_stories (%s) VALUES", paste(names(hn_clean), collapse = ", ")),
  paste0("  (", rows, ")", c(rep(",", length(rows) - 1), ";"))
)

writeLines(insert_sql, "sql/02_insert_data.sql", useBytes = TRUE)
cat(sprintf("Wrote sql/02_insert_data.sql with %d rows (%.0f KB)\n",
            nrow(hn_clean), file.size("sql/02_insert_data.sql") / 1024))